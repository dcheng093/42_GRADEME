import io
import contextlib


def run(module, check):
    cases = [
        # basic conversions
        (("0", 10, 2), "0"),
        (("1", 10, 2), "1"),
        (("10", 10, 2), "1010"),
        (("15", 10, 2), "1111"),
        (("16", 10, 2), "10000"),
        (("10", 2, 10), "2"),
        (("101", 2, 10), "5"),
        (("1111", 2, 10), "15"),
        (("10000", 2, 10), "16"),
        (("ff", 16, 10), "255"),

        # hexadecimal
        (("a", 16, 10), "10"),
        (("b", 16, 10), "11"),
        (("c", 16, 10), "12"),
        (("d", 16, 10), "13"),
        (("e", 16, 10), "14"),
        (("f", 16, 10), "15"),
        (("10", 16, 10), "16"),
        (("ff", 16, 10), "255"),
        (("100", 16, 10), "256"),
        (("abc", 16, 10), "2748"),

        # hex to binary
        (("f", 16, 2), "1111"),
        (("ff", 16, 2), "11111111"),
        (("10", 16, 2), "10000"),
        (("1a", 16, 2), "11010"),
        (("2f", 16, 2), "101111"),
        (("a5", 16, 2), "10100101"),
        (("dead", 16, 2), "1101111010101101"),
        (("beef", 16, 2), "1011111011101111"),
        (("1234", 16, 2), "1001000110100"),
        (("ffff", 16, 2), "1111111111111111"),

        # bbinary to hexadecimal
        (("1", 2, 16), "1"),
        (("10", 2, 16), "2"),
        (("1111", 2, 16), "F"),
        (("11111111", 2, 16), "FF"),
        (("1010", 2, 16), "A"),
        (("10101010", 2, 16), "AA"),
        (("11001100", 2, 16), "CC"),
        (("11110000", 2, 16), "F0"),
        (("10111110", 2, 16), "BE"),
        (("11011110", 2, 16), "DE"),

        # decimal to other bases
        (("10", 10, 16), "A"),
        (("15", 10, 16), "F"),
        (("16", 10, 16), "10"),
        (("31", 10, 16), "1F"),
        (("255", 10, 16), "FF"),
        (("256", 10, 16), "100"),
        (("10", 10, 8), "12"),
        (("15", 10, 8), "17"),
        (("64", 10, 8), "100"),
        (("255", 10, 8), "377"),

        # base 8
        (("10", 8, 10), "8"),
        (("17", 8, 10), "15"),
        (("20", 8, 10), "16"),
        (("77", 8, 10), "63"),
        (("100", 8, 10), "64"),
        (("377", 8, 10), "255"),
        (("10", 8, 2), "1000"),
        (("77", 8, 2), "111111"),
        (("100", 8, 16), "40"),
        (("377", 8, 16), "FF"),

        # other bases
        (("10", 3, 10), "3"),
        (("11", 3, 10), "4"),
        (("100", 3, 10), "9"),
        (("10", 4, 10), "4"),
        (("123", 4, 10), "27"),
        (("10", 5, 10), "5"),
        (("24", 5, 10), "14"),
        (("10", 7, 10), "7"),
        (("123", 7, 10), "66"),
        (("10", 36, 10), "36"),

        # base 36
        (("z", 36, 10), "35"),
        (("y", 36, 10), "34"),
        (("10", 36, 10), "36"),
        (("zz", 36, 10), "1295"),
        (("100", 36, 10), "1296"),
        (("abc", 36, 10), "13368"),
        (("Z", 36, 10), "35"),
        (("ABC", 36, 10), "13368"),
        (("10", 36, 16), "24"),
        (("zz", 36, 16), "50F"),

        # upper/lowercase input
        (("FF", 16, 10), "255"),
        (("Ff", 16, 10), "255"),
        (("fF", 16, 10), "255"),
        (("ABC", 16, 10), "2748"),
        (("abc", 16, 10), "2748"),
        (("AbC", 16, 10), "2748"),
        (("dead", 16, 10), "57005"),
        (("DEAD", 16, 10), "57005"),
        (("BeEf", 16, 10), "48879"),
        (("bEeF", 16, 10), "48879"),

        # leading zeros
        (("00", 10, 2), "0"),
        (("0000", 10, 16), "0"),
        (("00010", 10, 2), "1010"),
        (("00042", 10, 16), "2A"),
        (("000ff", 16, 10), "255"),
        (("0001010", 2, 10), "10"),
        (("00077", 8, 10), "63"),
        (("000z", 36, 10), "35"),
        (("0001", 2, 16), "1"),
        (("000f", 16, 2), "1111"),

        # same base
        (("0", 2, 2), "0"),
        (("1010", 2, 2), "1010"),
        (("123", 10, 10), "123"),
        (("255", 10, 10), "255"),
        (("ff", 16, 16), "FF"),
        (("abc", 16, 16), "ABC"),
        (("77", 8, 8), "77"),
        (("zz", 36, 36), "ZZ"),
        (("123", 4, 4), "123"),
        (("10101", 2, 2), "10101"),

        # invalid bases
        (("10", 1, 10), "ERROR"),
        (("10", 10, 1), "ERROR"),
        (("10", 0, 10), "ERROR"),
        (("10", 10, 0), "ERROR"),
        (("10", -2, 10), "ERROR"),
        (("10", 10, -2), "ERROR"),
        (("10", 37, 10), "ERROR"),
        (("10", 10, 37), "ERROR"),
        (("10", 100, 100), "ERROR"),
        (("10", -1, -1), "ERROR"),

        # invalid digits
        (("2", 2, 10), "ERROR"),
        (("102", 2, 10), "ERROR"),
        (("8", 8, 10), "ERROR"),
        (("89", 8, 10), "ERROR"),
        (("g", 16, 10), "ERROR"),
        (("1g", 16, 10), "ERROR"),
        (("z", 35, 10), "ERROR"),
        (("10", 2, 36), "2"),
        (("1a", 10, 16), "ERROR"),
        (("123", 2, 10), "ERROR"),
    ]

    for args, expected in cases:
        output = io.StringIO()

        with contextlib.redirect_stdout(output):
            result = module.convert_base(*args)

        actual = output.getvalue().strip()

        check(
            f"convert_base{args}",
            (actual, result),
            (expected, None),
        )
