def run(module, check):
    cases = [
        # basic numbers
        ("0", 0),
        ("1", 1),
        ("2", 2),
        ("9", 9),
        ("10", 10),
        ("42", 42),
        ("123", 123),
        ("999", 999),
        ("1000", 1000),
        ("12345", 12345),

        # positive sign
        ("+0", 0),
        ("+1", 1),
        ("+9", 9),
        ("+10", 10),
        ("+42", 42),
        ("+123", 123),
        ("+999", 999),
        ("+1000", 1000),
        ("+12345", 12345),
        ("+00042", 42),

        # negative numbers
        ("-0", 0),
        ("-1", -1),
        ("-9", -9),
        ("-10", -10),
        ("-42", -42),
        ("-123", -123),
        ("-999", -999),
        ("-1000", -1000),
        ("-12345", -12345),
        ("-00042", -42),

        # leading whitespace
        (" 0", 0),
        (" 1", 1),
        (" 42", 42),
        ("   123", 123),
        ("     999", 999),
        ("\t42", 42),
        ("\n42", 42),
        ("\t 42", 42),
        (" \t 123", 123),
        ("\n\t -42", -42),

        # whitespace + positive sign
        (" +1", 1),
        (" +42", 42),
        ("   +123", 123),
        ("\t+99", 99),
        (" \t+500", 500),
        ("   +00042", 42),
        ("\n+123", 123),
        ("\t +7", 7),
        (" \t +88", 88),
        ("    +9999", 9999),

        # whitespace + negative sign
        (" -1", -1),
        (" -42", -42),
        ("   -123", -123),
        ("\t-99", -99),
        (" \t-500", -500),
        ("   -00042", -42),
        ("\n-123", -123),
        ("\t -7", -7),
        (" \t -88", -88),
        ("    -9999", -9999),

        # stop at letters
        ("42abc", 42),
        ("123abc", 123),
        ("999xyz", 999),
        ("123hello", 123),
        ("-42abc", -42),
        ("+42abc", 42),
        ("  -42abc", -42),
        ("  +123xyz", 123),
        ("123abc456", 123),
        ("-123abc456", -123),

        # stop at punctuation
        ("42!", 42),
        ("123.", 123),
        ("123.45", 123),
        ("99,999", 99),
        ("42-10", 42),
        ("42+10", 42),
        ("123/456", 123),
        ("999#test", 999),
        ("100@home", 100),
        ("77$money", 77),

        # invalid / no digits
        ("", 0),
        ("abc", 0),
        ("hello", 0),
        ("+", 0),
        ("-", 0),
        ("+abc", 0),
        ("-abc", 0),
        ("   ", 0),
        ("\t", 0),
        ("\n", 0),

        # sign followed by whitespace
        ("+ 42", 0),
        ("- 42", 0),
        (" + 42", 0),
        (" - 42", 0),
        ("   +  42", 0),
        ("   -  42", 0),
        ("+\t42", 0),
        ("-\t42", 0),
        ("+ 123abc", 0),
        ("- 123abc", 0),

        # leading zeros
        ("00", 0),
        ("000", 0),
        ("0001", 1),
        ("00042", 42),
        ("00123", 123),
        ("000999", 999),
        ("-0001", -1),
        ("-00042", -42),
        ("+000123", 123),
        ("000000100", 100),

        # very large values
        ("123456789", 123456789),
        ("987654321", 987654321),
        ("1234567890", 1234567890),
        ("9999999999", 9999999999),
        ("-123456789", -123456789),
        ("-987654321", -987654321),
        ("-1234567890", -1234567890),
        ("999999999999", 999999999999),
        ("-999999999999", -999999999999),
        ("123456789012345", 123456789012345),

        # digits followed by whitespace
        ("42 ", 42),
        ("123  ", 123),
        ("999\t", 999),
        ("123\n", 123),
        ("-42 ", -42),
        ("+123 ", 123),
        ("42 abc", 42),
        ("123 hello", 123),
        ("-999 xyz", -999),
        ("+777 test", 777),
    ]

    for value, expected in cases:
        result = module.atoi(value)
        check(
            f"atoi({value!r})",
            result,
            expected
        )
