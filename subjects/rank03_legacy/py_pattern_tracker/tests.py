def run(module, check):

    cases = [
        # basic cases
        ("12", 1),
        ("23", 1),
        ("34", 1),
        ("89", 1),
        ("01", 1),
        ("99", 0),
        ("98", 0),
        ("21", 0),
        ("10", 0),

        # multiple patterns
        ("123", 2),
        ("1234", 3),
        ("12345", 4),
        ("123456789", 8),
        ("0123456789", 9),
        ("1123", 2),
        ("1223", 2),
        ("1233", 2),
        ("112233", 2),

        # broken sequences
        ("13", 0),
        ("14", 0),
        ("15", 0),
        ("124", 1),
        ("125", 1),
        ("132", 0),
        ("1235", 2),
        ("1245", 2),
        ("1357", 0),

        # letters between digits
        ("1a2", 0),
        ("1b2", 0),
        ("12a3", 1),
        ("1a23", 1),
        ("12a34", 2),
        ("123a4", 2),
        ("1a2b3", 0),
        ("a12", 1),
        ("12a", 1),
        ("a123", 2),
        ("123a", 2),

        # digits mixed with letters
        ("a1b2c3", 0),
        ("a12b34c", 2),
        ("12abc34", 2),
        ("abc123", 2),
        ("123abc", 2),
        ("a123z", 2),
        ("x12y23z", 2),

        # repeated and descending digits
        ("11", 0),
        ("22", 0),
        ("33", 0),
        ("44", 0),
        ("55", 0),
        ("66", 0),
        ("77", 0),
        ("88", 0),
        ("99", 0),
        ("9876543210", 0),
        ("54321", 0),
        ("210", 0),

        # special cases
        ("", 0),
        ("1", 0),
        ("a", 0),
        ("ab", 0),
        ("!", 0),
        ("!@#$", 0),
        ("12!", 1),
        ("!12", 1),
        ("1!2", 0),
        ("123!", 2),
        ("!123!", 2),
        (" 12 ", 1),
        ("1 2", 0),
        ("1\t2", 0),

        # longer mixed cases
        ("1234567890", 8),
        ("0987654321", 0),
        ("001122334455", 5),
        ("102132435465", 0),
        ("121314151617", 1),
        ("123abc456", 4),
        ("abc123xyz456", 4),
        ("12x34x56", 3),
        ("12-34-56", 3),
        ("12.34.56", 3),

        # boundary cases
        ("89a", 1),
        ("a89", 1),
        ("789", 2),
        ("789a", 2),
        ("a789", 2),
        ("6789", 3),
        ("67890", 3),
        ("78901", 3),

        # unicode and non-ascii characters
        ("1é2", 0),
        ("é12", 1),
        ("12é", 1),
        ("é123", 2),
        ("123é", 2),
    ]

    for value, expected in cases:
        check(
            f"pattern_tracker({value!r})",
            module.pattern_tracker(value),
            expected
        )
